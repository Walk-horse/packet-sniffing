package com.packetsniffer.packet_sniffing

import com.packetsniffer.packet_sniffing.CaptureBridge

/**
 * 接口模拟引擎：在代理层判定「这条请求是否要返回模拟响应」，并生成响应内容。
 *
 * 命中条件（全部满足）：
 *  1. 总开关开启，且发起请求的应用在「接口模拟」设置页被单独开启（mockApps 包含其包名）；
 *  2. 存在一条 enabled 的规则，其 method / host / path 与请求匹配（按具体度取第一条）。
 *
 * 响应示例：规则配置了 body 就用配置的；没配置则按「接口响应数据类型」生成默认占位示例。
 */
object MockEngine {

    data class MockResponse(
        val statusCode: Int,
        val statusText: String,
        val headers: List<Pair<String, String>>,
        val body: ByteArray,
        /** true = 响应体是按类型自动生成的示例（规则未配置示例） */
        val autoGenerated: Boolean
    )

    /** 匹配规则；无命中返回 null */
    fun match(uid: Int, method: String, host: String, path: String): MockRule? {
        if (!CaptureBridge.mockEnabled) return null
        if (!isUidMocked(uid)) return null
        val hits = CaptureBridge.mockRules.filter { rule ->
            rule.enabled &&
                methodMatches(rule.method, method) &&
                hostMatches(rule.host, host) &&
                pathMatches(rule.path, path)
        }
        if (hits.isEmpty()) return null
        // 更具体的规则优先：精确 path > 通配 path > 未配置 path。
        return hits.maxByOrNull { specificity(it.path) }
    }

    /** path 具体度：精确路径 2、含通配 1、空/全匹配 0；同级按字面长度更长者优先 */
    private fun specificity(path: String): Int {
        val p = path.trim()
        return when {
            p.isEmpty() || p == "*" -> 0
            p.contains('*') -> 1_000 + p.length
            else -> 1_000_000 + p.length
        }
    }

    /** 构造完整响应（含延迟与自定义头） */
    fun respond(rule: MockRule): MockResponse {
        if (rule.delayMs > 0) {
            runCatching { Thread.sleep(rule.delayMs.coerceAtMost(30_000L)) }
        }
        val custom = rule.body.isNotBlank()
        val bytes = if (custom) {
            rule.body.toByteArray(Charsets.UTF_8)
        } else {
            generateSample(rule.contentType)
        }
        val headers = buildList {
            add("Content-Type" to rule.contentType)
            addAll(rule.headers.filter { (k, _) ->
                !k.equals("Content-Length", true) && !k.equals("Connection", true) &&
                    !k.equals("Transfer-Encoding", true)
            })
        }
        return MockResponse(
            statusCode = rule.statusCode.takeIf { it in 100..599 } ?: 200,
            statusText = statusTextOf(rule.statusCode),
            headers = headers,
            body = bytes,
            autoGenerated = !custom
        )
    }

    /**
     * 是否存在针对该 host 的模拟规则。用于强制解密：
     * 即使「抓包模式」白/黑名单排除了该 host，只要有模拟规则也要 MITM，否则看不到请求就无法模拟。
     */
    internal fun shouldForceMitm(host: String): Boolean {
        if (!CaptureBridge.mockEnabled) return false
        return CaptureBridge.mockRules.any { it.enabled && hostMatches(it.host, host) }
    }

    // ================= 匹配 =================

    private fun isUidMocked(uid: Int): Boolean {
        if (uid < 0) return false
        val apps = CaptureBridge.mockApps
        if (apps.isEmpty()) return false
        val pkg = UidResolver.appPackageOf(uid)
        return pkg != null && pkg in apps
    }

    private fun methodMatches(rule: String, actual: String): Boolean {
        val r = rule.trim()
        return r.isEmpty() || r == "*" || r.equals(actual, true)
    }

    /** host 支持 *.example.com / .example.com 通配子域；空=不限 */
    private fun hostMatches(rule: String, actual: String): Boolean {
        val r = rule.trim().lowercase()
        if (r.isEmpty() || r == "*") return true
        val h = actual.lowercase()
        val target = h.substringBefore(':')
        return when {
            r.startsWith("*.") -> target == r.substring(2) || target.endsWith(r.substring(1))
            r.startsWith(".") -> target.endsWith(r)
            else -> target == r
        }
    }

    /** path 支持 * 通配；无 * 时按「完全相同」或「前缀 + /」匹配（自动忽略 query）。 */
    private fun pathMatches(rule: String, actual: String): Boolean {
        val r = rule.trim()
        if (r.isEmpty() || r == "*") return true
        val p = actual.substringBefore('?')
        if (r.contains('*')) return wildcardMatch(r, p)
        if (p == r) return true
        if (r == "/") return false
        return p.startsWith("$r/") || (r.endsWith("/") && p.startsWith(r))
    }

    /** 简易 glob：* 匹配任意字符序列 */
    private fun wildcardMatch(pattern: String, text: String): Boolean {
        val parts = pattern.split('*')
        if (parts.size == 1) return pattern == text
        var idx = 0
        for ((i, part) in parts.withIndex()) {
            if (part.isEmpty()) continue
            val found = text.indexOf(part, idx)
            if (found < 0) return false
            // 模式不以 * 开头时，第一段必须落在最前面
            if (i == 0 && found != 0) return false
            idx = found + part.length
        }
        val last = parts.last()
        return pattern.endsWith("*") || last.isEmpty() || text.endsWith(last)
    }

    // ================= 示例生成 =================

    /** 按响应数据类型生成默认示例（本地无历史样本源时直接给类型化占位）。 */
    private fun generateSample(contentType: String): ByteArray {
        return defaultSample(contentType.lowercase()).toByteArray(Charsets.UTF_8)
    }

    private fun defaultSample(contentType: String): String = when {
        contentType.contains("json") ->
            """{"code":0,"message":"mock","data":{}}"""
        contentType.contains("xml") ->
            """<?xml version="1.0" encoding="UTF-8"?><response><code>0</code><message>mock</message></response>"""
        contentType.contains("html") ->
            "<!DOCTYPE html><html><head><title>mock</title></head><body>mock</body></html>"
        contentType.startsWith("text/") -> "mock"
        else -> ""
    }

    fun statusTextOf(code: Int): String = when (code) {
        200 -> "OK"
        201 -> "Created"
        202 -> "Accepted"
        204 -> "No Content"
        301 -> "Moved Permanently"
        302 -> "Found"
        304 -> "Not Modified"
        400 -> "Bad Request"
        401 -> "Unauthorized"
        403 -> "Forbidden"
        404 -> "Not Found"
        405 -> "Method Not Allowed"
        408 -> "Request Timeout"
        409 -> "Conflict"
        429 -> "Too Many Requests"
        500 -> "Internal Server Error"
        502 -> "Bad Gateway"
        503 -> "Service Unavailable"
        504 -> "Gateway Timeout"
        else -> "Mock"
    }
}
